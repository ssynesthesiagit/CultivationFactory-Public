ROOT = Path(__file__).resolve().parents[1]


class _Weird(str):
    pass


class _Flag(int):
    pass


GOOD = [
    None, True, False, 0, -7, 2 ** 80, "", "plain", "café", "é decomposed", "中文", [], {}, (), (1, "a", None),
    {"b": [1, 2, {"z": None, "a": (True, "x")}], "a": "é", "é": 1},
    {"nested": {"deeper": [[["é"]], {"k": "é"}]}, "list": list(range(50)), "t": ("tuple", 1)},
    {"zeta": 1, "alpha": {"omega": [None, False], "beta": "ẛ̣"}},
    [_Weird("subclass"), _Flag(3)],
    {"x": _Weird("é")},
]
BAD = [1.5, {"a": 1.5}, [0.0], {1: "int key"}, {"a": {2: "x"}}, {"é": 1, "é": 2}, {"a": object()}, [set()], b"bytes", {"a": [1, [2, 1e3]]}]


@pytest.mark.parametrize("value", GOOD, ids=lambda v: repr(v)[:40])
def test_canonical_bytes_are_identical_with_and_without_the_fast_path(value):
    # what canonical_bytes wrote before the fast path: always through the normalising copy
    expected = json.dumps(canonical._normalize(value), ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")
    assert canonical_bytes(value) == expected
    assert canonical_sha256(value) == canonical_sha256(copy.deepcopy(value))


@pytest.mark.parametrize("value", BAD, ids=lambda v: repr(v)[:40])
def test_canonical_bytes_reject_exactly_what_they_rejected_before(value):
    with pytest.raises(CanonicalValueError) as fast:
        canonical_bytes(value)
    with pytest.raises(CanonicalValueError) as slow:
        canonical._normalize(value)
    assert str(fast.value) == str(slow.value)  # the same message, with the same path


def test_the_fast_path_only_accepts_already_canonical_documents():
    assert canonical._already_canonical({"a": [1, "b", None, True, {"c": ()}]})
    assert not canonical._already_canonical({"a": 1.0})
    assert not canonical._already_canonical({"a": "é"})  # not NFC: it must be normalised
    assert not canonical._already_canonical({"é": 1})
    assert not canonical._already_canonical({1: 1})
    assert not canonical._already_canonical([_Flag(1)])
    assert not canonical._already_canonical(object())
    assert unicodedata.is_normalized("NFC", "é")


class _Counter:
    """Counts what a table answer costs: fights loaded, and legal-candidate lists actually generated by the engine."""

    def __init__(self, monkeypatch):
        self.loads = 0
        self.generated = 0
        self.monkeypatch = monkeypatch
        generate = Gate4ControllerEngine.legal_candidates
        counter = self

        def counting_generate(engine):
            counter.generated += 1
            return generate(engine)

        monkeypatch.setattr(Gate4ControllerEngine, "legal_candidates", counting_generate)

    def watch(self, combat):
        load = combat.persistence.load_match
        counter = self

        def counting_load(*args, **kwargs):
            counter.loads += 1
            return load(*args, **kwargs)

        self.monkeypatch.setattr(combat.persistence, "load_match", counting_load)
        return combat

    def reset(self):
        self.loads = self.generated = 0


def _fight(tmp_path, seed="SPEED-TEST"):
    _install(tmp_path, "left")
    _install(tmp_path, "right")
    combat = CombatService(ROOT, tmp_path)
    combat.tabletop_maps.save(MAP)
    table = TabletopService(combat, tmp_path)
    view = combat.create_factory_match(project_ids=["left"], opponent_actor_ids=[FACTORY_ACTOR_PREFIX + "right"],
                                       control_modes={FACTORY_ACTOR_PREFIX + "left": "MANUAL"}, arena_id="battlefield:map.courtyard",
                                       match_seed=seed)
    return combat, table, view["match_id"]


def _to_the_humans_turn(table, match_id):
    state, after = table.state(match_id), 0
    for _ in range(12):
        if state["menu"] and state["menu"].get("manual"):
            return state, after
        result = table.auto_step(match_id, after)
        after, state = result["events"]["last_sequence"], result["state"]
    raise AssertionError("it never became the human's turn")


def test_a_table_answer_loads_the_fight_once_and_works_out_its_candidates_once_per_state(tmp_path, monkeypatch):
    combat, table, match_id = _fight(tmp_path)
    state, after = _to_the_humans_turn(table, match_id)
    counter = _Counter(monkeypatch)
    counter.watch(combat)

    table.state(match_id)  # a state already asked for: nothing is generated again, the fight is loaded once
    assert (counter.loads, counter.generated) == (1, 0)
    assert table.state(match_id)["menu"] == state["menu"]

    # A fresh service (no cache) works out the candidates once for the whole answer: presentation, menu and the
    # submit checks all read the same list.
    counter.reset()
    TabletopService(counter.watch(CombatService(ROOT, tmp_path)), tmp_path).state(match_id)
    assert counter.generated == 1

    # Acting loads the fight for the check and the commit together, then once more for the new state.
    menu = state["menu"]
    counter.reset()
    table.act(match_id, menu["moves"][0]["candidate_id"], menu["decision_id"], menu["state_version"], after)
    assert counter.loads <= 2


@pytest.mark.parametrize("kind", ["move", "end_turn"])
def test_manual_answer_reuses_its_engine_without_changing_the_feed(tmp_path, monkeypatch, kind):
    """DEX1's named-damage profiles must not add a third load to C2's answer.

    The journal, standalone poll and fresh-service answer still agree exactly.
    Reusing an engine must not mutate either it or the saved fight.
    """
    combat, table, match_id = _fight(tmp_path)
    state, after = _to_the_humans_turn(table, match_id)
    menu = state["menu"]
    candidate = menu["moves"][0]["candidate_id"] if kind == "move" else menu["end_turn"]
    counter = _Counter(monkeypatch)
    counter.watch(combat)
    result = table.act(match_id, candidate, menu["decision_id"], menu["state_version"], after)
    assert result["status"] == "COMMITTED"
    assert counter.loads == 1  # measured: the act's single load; the feed answers from the committed engine
    assert counter.generated == 1

    fresh = CombatService(ROOT, tmp_path)
    fresh_table = TabletopService(counter.watch(fresh), tmp_path)
    counter.reset()
    assert fresh_table.events(match_id, after) == result["events"]
    assert counter.loads == 1  # standalone polls still load their current engine
    assert fresh_table.state(match_id) == result["state"]

    session = fresh._load_session(match_id)
    engine_before = canonical_bytes(session.engine.state.model_dump(mode="json", by_alias=True))
    from tests.tree_hash_support import _tree_hashes

    storage_before = _tree_hashes(session.mechanical.store.match_dir)
    counter.reset()
    assert fresh_table.events(match_id, after, engine=session.engine) == result["events"]
    assert counter.loads == 0
    assert canonical_bytes(session.engine.state.model_dump(mode="json", by_alias=True)) == engine_before
    assert _tree_hashes(session.mechanical.store.match_dir) == storage_before
    assert fresh.verify(match_id)["status"] == "PASS"
    assert fresh.replay(match_id)["status"] == "PASS"


def test_manual_decision_pause_reuses_the_unchanged_engine(tmp_path, monkeypatch):
    """Ask-me responses use the loaded engine without committing or changing text."""
    from tests.r10_fixup_support import cast_sender, commit, fixed_dice
    from tests.test_carry import KIT
    from tests.test_tabletop_hunt6 import LEFT, RIGHT, table_fight
    from tests.tree_hash_support import _tree_hashes

    combat, table, match_id = table_fight(
        tmp_path, ["TAL_FENCING_TO_THE_HILT", "TAL_FENCING_ANKLE_STRIKE", "TAL_FENCING_EXPERT_FEINT"],
        kit={"starting_kit": KIT}, ask=True, ally_talents=[])
    fixed_dice(monkeypatch, [19, 19, *([1] * 40)])
    commit(cast_sender(combat, table, match_id, "Feint (Bonus Action)"), lambda p: (LEFT, True))
    send = cast_sender(combat, table, match_id, "Bi Shou (Dagger) attack", target=RIGHT)
    saved = combat._load_session(match_id)
    before = _tree_hashes(saved.mechanical.store.match_dir)
    counter = _Counter(monkeypatch)
    counter.watch(combat)
    result = send()
    assert result["status"] == "REACTION_REQUIRED"
    assert counter.loads == 2
    after_pause = _tree_hashes(saved.mechanical.store.match_dir)
    # Ask-me now persists the retry reservation, while committed fight files
    # stay byte-identical. This permits the same choice after a table reload.
    assert {k: v for k, v in after_pause.items() if k != 'Tabletop_Pending_Action.json'} == before
    assert 'Tabletop_Pending_Action.json' in after_pause
    assert result["reaction"]["context"]["reaction_source_id"] == "choice:needle.exploit"
    assert "Right" in result["reaction"]["trigger"] and "Bi Shou" in result["reaction"]["trigger"]
    fresh = TabletopService(CombatService(ROOT, tmp_path), tmp_path)
    fresh_send = cast_sender(fresh.combat, fresh, match_id, "Bi Shou (Dagger) attack", target=RIGHT)
    assert fresh_send() == result
    assert _tree_hashes(saved.mechanical.store.match_dir) == after_pause


def test_a_commit_moves_the_cache_on_and_a_stale_decision_is_still_refused(tmp_path):
    combat, table, match_id = _fight(tmp_path)
    state, after = _to_the_humans_turn(table, match_id)
    menu = state["menu"]
    before = combat.decision(match_id)
    edited = combat.decision(match_id)
    edited["context"]["legal_candidates"].clear()  # a caller may edit what it was given (the table does)
    assert combat.decision(match_id) == before

    result = table.act(match_id, menu["moves"][0]["candidate_id"], menu["decision_id"], menu["state_version"], after)
    assert result["status"] == "COMMITTED"
    now = combat.decision(match_id)
    assert now["context"]["state_version"] > before["context"]["state_version"]
    assert now["context"]["decision_id"] != before["context"]["decision_id"]
    assert now["context"]["legal_candidates"] and now["context"]["legal_candidates"] != before["context"]["legal_candidates"]
    assert result["state"]["menu"]["state_version"] == now["context"]["state_version"]
    from combat.tabletop import TabletopError

    with pytest.raises(TabletopError) as error:
        table.act(match_id, menu["moves"][0]["candidate_id"], menu["decision_id"], menu["state_version"], after)
    assert error.value.code == "TABLETOP_STALE"


def test_what_is_cached_is_exactly_what_a_fresh_service_answers(tmp_path):
    combat, table, match_id = _fight(tmp_path)
    state, after = _to_the_humans_turn(table, match_id)
    table.state(match_id)  # warm the cache
    cached = table.state(match_id)
    fresh_combat = CombatService(ROOT, tmp_path)
    fresh = TabletopService(fresh_combat, tmp_path).state(match_id)
    assert cached == fresh
    assert combat.decision(match_id) == fresh_combat.decision(match_id)
    assert combat.presentation(match_id) == fresh_combat.presentation(match_id)


def test_the_live_presentation_without_its_feed_is_the_full_one_minus_the_feed(tmp_path):
    combat, table, match_id = _fight(tmp_path)
    _to_the_humans_turn(table, match_id)
    full = combat.presentation(match_id)
    lean = combat.presentation(match_id, feed=False)
    assert full["feed"], "the fight has history, so the full presentation has a feed"
    assert lean["feed"] == []
    assert {key: value for key, value in full.items() if key != "feed"} == {key: value for key, value in lean.items() if key != "feed"}
    # a historical boundary keeps its feed whatever is asked
    assert combat.presentation(match_id, boundary_index=0, feed=False)["feed"] == combat.presentation(match_id, boundary_index=0)["feed"]
    # the table's own answer does not depend on the feed
    assert "feed" in table.state(match_id)["presentation"]


def test_the_journal_is_the_same_whether_or_not_the_cache_is_used(tmp_path_factory):
    """The same fight, played by the same steps on two services -- one that keeps its cache between answers and one that is
    rebuilt (empty cache) for every answer -- leaves byte-identical journals."""
    journals = []
    for rebuild in (False, True):
        root = tmp_path_factory.mktemp("rebuild" if rebuild else "keep")
        combat, table, match_id = _fight(root, seed="SPEED-JOURNAL")
        for _ in range(4):
            if rebuild:
                combat = CombatService(ROOT, root)
                table = TabletopService(combat, root)
            state = table.state(match_id)
            menu = state["menu"]
            if menu and menu.get("manual"):
                table.act(match_id, menu["end_turn"], menu["decision_id"], menu["state_version"], 0)
            else:
                table.auto_step(match_id, 0)
        (journal,) = list((root / "Combat" / "Matches").glob("*/Journal.ndjson"))
        text = journal.read_text(encoding="utf-8").replace(match_id, "MATCH")
        journals.append([json.loads(line) for line in text.splitlines() if line.strip()])
    assert journals[0] == journals[1]
    assert len(journals[0]) > 5


@pytest.mark.parametrize("kind", ["move", "end_turn"])
def test_execution_candidate_reuse_preserves_the_full_result_and_journal(tmp_path_factory, kind):
    results, journals = [], []
    for reuse in (False, True):
        root = tmp_path_factory.mktemp("memo" if reuse else "plain")
        combat, table, match_id = _fight(root, seed="C2-EXECUTION-EQUIVALENCE")
        state, after = _to_the_humans_turn(table, match_id)
        menu = state["menu"]
        if not reuse:
            combat._execution_candidates = lambda *args: nullcontext()
        candidate = menu["moves"][0]["candidate_id"] if kind == "move" else menu["end_turn"]
        result = table.act(match_id, candidate, menu["decision_id"], menu["state_version"], after)
        results.append(json.dumps(result, sort_keys=True).replace(match_id, "MATCH"))
        (journal,) = list((root / "Combat" / "Matches").glob("*/Journal.ndjson"))
        journals.append(journal.read_text().replace(match_id, "MATCH"))
    assert results[0] == results[1]
    assert journals[0] == journals[1]


def test_execution_memo_checks_changes_inside_a_transaction_and_restores_on_failure(tmp_path):
    combat, table, match_id = _fight(tmp_path)
    _to_the_humans_turn(table, match_id)
    session = combat._load_session(match_id)
    engine = session.engine
    candidates = combat._legal_candidates(session)
    digest = canonical_sha256(engine.state.model_dump(mode="json", by_alias=True))
    calls = []
    fallback = object()

    def generate():
        calls.append(True)
        return fallback

    engine.legal_candidates = generate
    version = engine.state.state_version
    actor = engine.state.actors[engine.state.current_actor_id]
    with pytest.raises(RuntimeError):
        with combat._execution_candidates(engine, candidates, digest):
            assert engine.legal_candidates() is candidates
            actor.position = actor.position.model_copy(update={"x": actor.position.x + 1})  # an effect before the version advances
            assert engine.state.state_version == version
            assert engine.legal_candidates() is fallback
            assert len(calls) == 1
            raise RuntimeError("test failure")
    assert engine.legal_candidates is generate


