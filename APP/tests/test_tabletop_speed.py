def test_execution_memo_prepares_wall_geometry_on_a_preview_clone(tmp_path):
    from combat.gate2_runtime_models import Position, ZoneState
    from combat.zones import sync_walls

    combat, table, match_id = _fight(tmp_path)
    _to_the_humans_turn(table, match_id)
    engine = combat._load_session(match_id).engine
    cell = Position(x=3, y=3)
    zone = ZoneState(zone_id="zone:c2.wall", source_definition_id="test:c2.wall", owner_id=engine.state.current_actor_id,
                     center=cell, radius_cells=0, affected_cells=(cell,), concentration_link=False,
                     created_round=engine.state.round_number,
                     trigger_profile={"kind": "TYPED", "wall": {"blocks_movement": True, "cover": "three_quarters"}})
    engine.state.zones[zone.zone_id] = zone
    sync_walls(engine)
    candidates = engine.legal_candidates()
    clone = combat._clone_engine(ROOT, engine)
    digest = canonical_sha256(engine.state.model_dump(mode="json", by_alias=True))
    with combat._execution_candidates(clone, candidates, digest):
        assert clone.grid.blocked == engine.grid.blocked
        assert clone.grid.cover == engine.grid.cover
        assert clone._cover_three_quarters == engine._cover_three_quarters
        assert clone.legal_candidates() is candidates
