"""Tabletop speed (owner playtest 2026-09-29: a big fight took 15-37 s per action).

What is worked out from one saved state of a fight (its legal candidates, the decision menu) is worked out once and reused
until the fight's journal moves on; a table answer loads the fight once; the live boundary's history feed (a replay of the
whole journal) is skipped where the table does not read it; and the canonical JSON writer no longer builds a normalised copy
of a document that is already canonical.  None of it may change a result: these tests pin the exact equivalences."""

