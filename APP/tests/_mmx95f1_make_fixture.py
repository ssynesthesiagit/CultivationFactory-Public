"""Regenerate the committed augment fixture straight from the production builders.

Run:  python APP/tests/_mmx95f1_make_fixture.py
"""
import json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from combat import tabletop as tt
from combat.tabletop_service import TabletopService
from tests.test_auto_tabik import _engine, ME

OUT = Path(__file__).with_name("fixtures") / "mmx95f1_augment_payload.json"

TALENTS = ["TAL_DARK_CLINGING_DARKNESS", "TAL_DARK_ETERNAL_DARKNESS", "TAL_DARK_NUMBING_DARKNESS"]


def build():
    engine, _ = _engine(TALENTS)
    toggles = [a for a in engine.action_catalog.values()
               if (a.parameters or {}).get("augment_toggle") and (a.parameters or {}).get("augment_key")]
    shapes = [a for a in engine.action_catalog.values() if (a.parameters or {}).get("zone_shape")]

    def payload(action):
        return tt._augment_button(
            {"source_definition_id": action.source_definition_id, "display_name": action.display_name,
             "parameters": action.parameters},
            {action.parameters["augment_toggle"]: (action.parameters.get("augment_loadout") or {})})

    clinging = next(a for a in toggles if "CLINGING" in json.dumps(a.parameters, default=str).upper())
    eternal = next(a for a in toggles if "ETERNAL" in json.dumps(a.parameters, default=str).upper())

    # The real menu, so the fixture carries the real option count and shape.
    cands = engine.legal_candidates()
    legal = [{"kind": getattr(c, "kind", "ACTION"), "candidate_id": c.candidate_id,
              "source_definition_id": c.source_definition_id,
              "target_ids": list(getattr(c, "target_ids", []) or []),
              "destination": getattr(c, "destination", None), "area": getattr(c, "area", None) or None,
              "option_ids": list(getattr(c, "option_ids", []) or []),
              "display_name": getattr(c, "display_name", None),
              "metadata": getattr(c, "metadata", None) or {}} for c in cands]
    first = cands[0] if cands else None
    decision = {"control_mode": "MANUAL", "reactions_available": [],
                "context": {"legal_candidates": legal, "active_actor_id": ME,
                            "decision_id": getattr(first, "decision_id", "d1"),
                            "state_version": getattr(first, "state_version", 1)}}
    menu = TabletopService._menu(decision, {}, None, engine)

    def group_for(source):
        return next(g for g in menu["actions"] if g["source_definition_id"] == source)

    return {
        "_comment": "Generated by APP/tests/_mmx95f1_make_fixture.py from combat/tabletop.py _augment_button and the real "
                    "TabletopService._menu. Do not hand-edit: tests/test_mmx95_sheet_turn_refusal.py regenerates it and "
                    "fails on any drift. candidate_ids are engine-generated and are not compared.",
        "actor_id": ME,
        "augment_clinging": payload(clinging),
        "augment_eternal": payload(eternal),
        "menu_group_clinging": {k: v for k, v in group_for(clinging.source_definition_id).items() if k != "options"},
        "menu_group_option_clinging": [{k: v for k, v in o.items() if k != "candidate_id"}
                                       for o in group_for(clinging.source_definition_id)["options"]],
        "menu_group_clinging_option_count": len(group_for(clinging.source_definition_id)["options"]),
        "base_action_id": clinging.parameters["augment_toggle"],
    }


if __name__ == "__main__":
    data = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
    print("wrote", OUT)
    print("clinging button has 'shape':", "shape" in data["augment_clinging"])
    print("clinging option count:", data["menu_group_clinging_option_count"])
