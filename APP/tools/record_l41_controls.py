"""Record the L41 replay controls using the same fixture and checks as the test.

Run from APP: python tools/record_l41_controls.py <output_module>
"""
import argparse
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from combat.canonical import canonical_text


def control_stream(lines, final):
    """Keep every event, roll, genesis payload and final state inspectable."""
    return "\n".join([*lines, canonical_text(final)]) + "\n"


def write_controls(output_module, streams):
    """Write captured streams; also used to retain a failing replay's actual control."""
    module = '"""Recorded L41 replay controls; generated by tools/record_l41_controls.py."""\n\nCONTROL_STREAMS = {\n'
    for seed, stream in streams.items():
        module += f"    {seed!r}: (\n"
        module += "".join(f"        {line!r}\n" for line in stream.splitlines(keepends=True))
        module += "    ),\n"
    output_module.write_text(module + "}\n", encoding="utf-8")


def main():
    import pytest

    from tests.legacy_fight_support import apply_legacy_zero_hp
    from tests.test_l41_ai_replay import SEEDS, capture_l41_control

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output_module", type=Path)
    args = parser.parse_args()
    streams = {}
    with pytest.MonkeyPatch.context() as patch:
        apply_legacy_zero_hp(patch)
        for seed in SEEDS:
            with tempfile.TemporaryDirectory(prefix="l41-control-") as work:
                lines, final = capture_l41_control(Path(work), seed)
            streams[seed] = control_stream(lines, final)
    write_controls(args.output_module, streams)


if __name__ == "__main__":
    main()
