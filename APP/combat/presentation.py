def _humanize(value: str | None) -> str:
    if not value:
        return ""
    tail = str(value).split(":")[-1].split(".")[-1]
    return " ".join(part.capitalize() for part in tail.replace("-", "_").split("_") if part)


def _initials(display_name: str) -> str:
    pieces = [piece for piece in display_name.split() if piece]
    return "".join(piece[0] for piece in pieces[:2]).upper() or "?"


def _source_category(identifier: str, fallback: str = "ACTION") -> str:
    prefix = identifier.split(":", 1)[0].upper() if ":" in identifier else fallback
    return {
        "ACTION": "ACTION",
        "TALENT": "SPHERE_TALENT",
        "REACTION": "REACTION",
        "SYSTEM": "BASIC_ACTION",
        "CREATURE": "COMPANION_ACTION",
    }.get(prefix, fallback)


