class CombatPresentationProjection(StrictModel):
    schema_name: Literal[PRESENTATION_SCHEMA] = Field(default=PRESENTATION_SCHEMA, alias="schema")
    match_id: str
    display_name: str
    mode: Literal["LIVE", "HISTORY"]
    state_version: int
    boundary: HistoricalBoundaryProjection | None = None
    round_number: int
    current_slot_index: int
    current_actor_id: str | None = None
    paused: bool
    terminal: bool
    terminal_result: dict[str, Any] | None = None
    battlefield: BattlefieldGeometryProjection
    map_visual: MapVisualProjection | None = None
    teams: tuple[TeamPresentation, ...]
    actors: tuple[CombatSheetProjection, ...]
    initiative_order: tuple[str, ...]
    zones: tuple[dict[str, Any], ...]
    feed: tuple[dict[str, Any], ...]
    findings: tuple[PresentationFinding, ...] = ()

    @model_validator(mode="after")
    def validate_identity(self) -> "CombatPresentationProjection":
        actor_ids = [actor.entity_id for actor in self.actors]
        if len(actor_ids) != len(set(actor_ids)):
            raise ValueError("duplicate actor entity_id in presentation projection")
        if len(self.initiative_order) != len(set(self.initiative_order)):
            raise ValueError("duplicate initiative actor ID")
        missing = set(self.initiative_order) - set(actor_ids)
        if missing:
            raise ValueError(f"initiative references missing actors: {sorted(missing)}")
        if self.current_actor_id is not None and self.current_actor_id not in set(actor_ids):
            raise ValueError("current actor missing from presentation actors")
        return self


