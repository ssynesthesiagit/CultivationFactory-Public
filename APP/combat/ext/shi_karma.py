"""Karma Knot Root Foundation: Generate Karmic Due (owner 2026-09-28, "automate every aspect before another
playtest"). Shi Xunyun.

"Once per round, after you hit a creature or it fails a saving throw against your technique, if that
creature damaged you or an ally since the end of your last turn, gain 1 Karmic Due, maximum 1. It fades at
the end of your next turn... Cannot be spent on the same hit or failed save that generated it."

combat/pressure.py already generates a Foundation resource on a hit ("hit_aggressor"), but only for a melee
hit within the actor's own reach against a creature that pressed the actor itself -- narrower than this
talent's "hit or failed save, ranged included, you or an ally". Reusing that block/column as-is would either
miss Shi Xunyun's ranged Lightning attacks and ally-only presses, or (if widened) change what Ancient
Desolate Sacred Body's Golden Sea Pulse generates on for a character this task does not own. So this is its
own small mechanism instead of a widened shared block.

Knot Judgment and Red Cord Guard (the Due's two other spenders) already work through the ordinary typed
modifier/reaction pipeline once the Due exists; nothing else needed changing for them. Since the gain here
runs from the ``after_hit``/``after_save`` hooks -- which fire once a typed attack's own on-hit effects
(including a modifier like Knot Judgment) have already resolved -- the Due generated by this hit is not
available to spend on this same hit, matching "cannot be spent on the same event that generated it" without
extra bookkeeping.
"""

from __future__ import annotations

from typing import Any

from . import hook

RESOURCE = "resource:foundation.karmic_due"
BLOCK = "shi_karma_generate"
EXPIRY_FLAG = "shi_karma_due_expiry"


def _rows(engine: Any, actor: Any, block: str) -> list[dict[str, Any]]:
    from .. import typed_reactions

    return typed_reactions._rows(engine, actor.entity_id, block)


def _pressed(engine: Any, actor: Any, target: Any) -> bool:
    """Whether ``target`` damaged ``actor`` or one of ``actor``'s living allies since the end of actor's last
    turn (combat/pressure.py's ``_pressed_by`` checks only the actor itself; this also checks allies)."""
    starts = 0
    for event in reversed(engine.events):
        if event.event_type == "TURN_STARTED" and event.actor_id == actor.entity_id:
            starts += 1
            if starts >= 2:
                return False
        if event.actor_id != target.entity_id or event.event_type != "DAMAGE_COMMITTED":
            continue
        for subject_id in event.target_ids or ():
            if subject_id == actor.entity_id:
                return True
            subject = engine.state.actors.get(subject_id)
            if subject is not None and subject.team_id == actor.team_id:
                return True
    return False


def _generate(engine: Any, actor: Any) -> None:
    if not _rows(engine, actor, BLOCK) or not actor.active or actor.current_hp <= 0:
        return
    if actor.turn_flags.get("shi_karma_due_round") == engine.state.round_number:
        return  # "Once per round"
    actor.turn_flags["shi_karma_due_round"] = engine.state.round_number
    if actor.resources.get(RESOURCE, 0) < 1:
        engine._gain_resource(actor, RESOURCE, 1, "passive:foundation.karma_knot_root_v0_2B.generate_karmic_due")
    own_turn = engine.state.current_actor_id == actor.entity_id
    actor.turn_flags[EXPIRY_FLAG] = 2 if own_turn else 1  # "fades at the end of your next turn"


@hook("after_hit")
def _after_hit(ctx: Any, target: Any, kind: str) -> None:
    if _pressed(ctx.engine, ctx.actor, target):
        _generate(ctx.engine, ctx.actor)


@hook("after_save")
def _after_save(ctx: Any, subject: Any, ability: str, named: Any, failed: bool) -> None:
    if failed and subject.team_id != ctx.actor.team_id and _pressed(ctx.engine, ctx.actor, subject):
        _generate(ctx.engine, ctx.actor)


@hook("turn_end")
def _turn_end(engine: Any, actor: Any) -> None:
    if EXPIRY_FLAG not in actor.turn_flags:
        return
    left = int(actor.turn_flags[EXPIRY_FLAG]) - 1
    if left <= 0:
        del actor.turn_flags[EXPIRY_FLAG]
        held = int(actor.resources.get(RESOURCE, 0) or 0)
        if held:
            engine._spend_resource(actor, RESOURCE, held, "passive:foundation.karma_knot_root_v0_2B.generate_karmic_due.expired")
    else:
        actor.turn_flags[EXPIRY_FLAG] = left


@hook("compile_block")
def _compile_block(block: str, spec: dict[str, Any], row: dict[str, Any], numbers: dict[str, Any]) -> list[dict[str, Any]] | None:
    if block == BLOCK:
        return [dict(row)]
    return None
