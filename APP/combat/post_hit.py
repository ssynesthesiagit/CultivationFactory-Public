"""Strict paid post-hit checkpoint for Origin-Seizing Blow and similar riders."""
from dataclasses import dataclass
from . import ext
from .damage_context import AttackDamage


@dataclass(frozen=True)
class SettledHit:
    attack: AttackDamage
    damage_type: str
    resources_before: tuple

    def resource_before(self, actor_id, resource_id):
        return dict(dict(self.resources_before).get(actor_id, ())).get(resource_id, 0)


def resolve(engine, actor, target, spec, intent, before):
    """After primary hit damage, before old notifications; not called on misses.

    Consumers own alignment/meaningful-target checks, consent, costs, added
    damage and post-damage threshold checks. The original resource snapshot
    prevents spending a resource first generated by this same hit.
    """
    attack = spec.get('resolved_attack_context')
    if not isinstance(attack, AttackDamage) or not ext.has('post_hit_damage'):
        return
    packet = SettledHit(attack, str(spec.get('damage_type') or 'UNTYPED'), before)
    for result in ext.run_checkpoint('post_hit_damage', engine, actor, target, packet, intent):
        if result is not None:
            raise ext.CheckpointError('Post-hit damage consumers must return None')
